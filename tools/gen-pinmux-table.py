#!/usr/bin/env python3
"""Generate WinRT/drivers/goyapinmux/pinmux_table.h from the vendor-kernel DT pin groups.

usage: gen-pinmux-table.py <pxa988-pinfunc.h> <pxa986-samsung-goyawifi-pins.dtsi> <out.h>

Each pin of each group becomes one entry {MFPR offset, clear mask, set value, group index}.
Pin configuration semantics follow pinctrl-single: AF in bits [2:0]; bias-pullup uses the
"enabled" cell (cell 1) under mask PULL_MASK; drive-strength / low-power-mode use cell 0 / mask.
"""
import re, sys

hdr, dts, out = sys.argv[1:4]
defs = {}
for l in open(hdr):
    m = re.match(r'#define\s+(\w+)\s+(0x[0-9a-fA-F]+|\d+)\b', l)
    if m:
        defs[m.group(1)] = int(m.group(2), 0)

def val(tok):
    tok = tok.strip()
    if tok in defs:
        return defs[tok]
    return int(tok, 0)

text = open(dts).read()
groups = []
for m in re.finditer(r'(\w+):\s*[\w-]+\s*\{(.*?)\n\t\};', text, re.S):
    name, body = m.group(1), m.group(2)
    pins = re.search(r'pinctrl-single,pins\s*=\s*<(.*?)>;', body, re.S)
    if not pins:
        continue
    plist = []
    for l in pins.group(1).splitlines():
        l = re.sub(r'/\*.*?\*/', '', l).strip()
        if not l:
            continue
        a, b = l.split()[:2]
        plist.append((a, val(a), val(b)))
    def prop(n):
        p = re.search(r'pinctrl-single,%s\s*=\s*<(.*?)>;' % n, body, re.S)
        return [val(t) for t in p.group(1).split()] if p else None
    groups.append((name, plist, prop('bias-pullup'), prop('drive-strength'), prop('low-power-mode')))

entries = []
for gi, (name, plist, pull, ds, lpm) in enumerate(groups):
    for pname, off, af in plist:
        clr, setv = 0x7, af
        if pull:
            clr |= pull[3]; setv |= pull[1]
        if ds:
            clr |= ds[1]; setv |= ds[0]
        if lpm:
            clr |= lpm[1]; setv |= lpm[0]
        entries.append((off, clr, setv, gi, pname, name))

with open(out, 'w') as f:
    f.write('/* Generated by tools/gen-pinmux-table.py from the vendor DT pin groups - do not edit. */\n')
    f.write('typedef struct _PINMUX_ENTRY { USHORT Offset; USHORT Clear; USHORT Set; UCHAR Group; UCHAR Pad; } PINMUX_ENTRY;\n')
    f.write('#define PINMUX_GROUP_COUNT %d\n' % len(groups))
    for gi, g in enumerate(groups):
        f.write('#define PINMUX_GROUP_%s %d\n' % (g[0].upper(), gi))
    f.write('static const PINMUX_ENTRY gPinmuxTable[] = {\n')
    for off, clr, setv, gi, pname, name in entries:
        f.write('    { 0x%04X, 0x%04X, 0x%04X, %d, 0 }, /* %s: %s */\n' % (off, clr, setv, gi, name, pname))
    f.write('};\n')
print('%d groups, %d pins' % (len(groups), len(entries)))
