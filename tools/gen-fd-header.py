"""
Assemble Platform/Samsung/GoyaWifiPkg/Header/FdHeader.S and emit
FdHeader.fdf.inc, the DATA block placed at offset 0 of the FD.

  tools/gen-fd-header.py [--cc arm-linux-gnueabihf-gcc]
"""
import argparse, os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
HDR = os.path.join(HERE, "..", "Platform", "Samsung", "GoyaWifiPkg", "Header")

ap = argparse.ArgumentParser()
ap.add_argument("--cc", default=os.environ.get("GCC_ARM_PREFIX", "arm-linux-gnueabihf-") + "gcc")
ap.add_argument("--fd-base", default="0x10008000")
ap.add_argument("--fd-size", default="0x00200000")
a = ap.parse_args()
objcopy = a.cc[:-3] + "objcopy"

with tempfile.TemporaryDirectory() as t:
    obj, binf = os.path.join(t, "h.o"), os.path.join(t, "h.bin")
    subprocess.check_call([a.cc, "-c", "-march=armv7-a+fp", "-marm",
                           f"-DFD_BASE={a.fd_base}", f"-DFD_SIZE={a.fd_size}",
                           "-o", obj, os.path.join(HDR, "FdHeader.S")])
    subprocess.check_call([objcopy, "-O", "binary", "-j", ".text", obj, binf])
    data = open(binf, "rb").read()

if len(data) > 0x1000:
    sys.exit("header larger than 4 KiB")

lines = ["## @file", "#  GENERATED by tools/gen-fd-header.py from Header/FdHeader.S - do not edit.",
         "#  Self-relocating zImage-compatible FD header.", "#",
         "#  SPDX-License-Identifier: BSD-2-Clause-Patent", "##", "DATA = {"]
for i in range(0, len(data), 8):
    chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 8])
    lines.append(f"  {chunk}{',' if i + 8 < len(data) else ''}")
lines.append("}")
out = os.path.join(HDR, "FdHeader.fdf.inc")
open(out, "w").write("\n".join(lines) + "\n")
print(f"{out}: {len(data)} bytes")
